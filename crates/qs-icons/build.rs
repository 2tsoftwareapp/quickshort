//! Vendored Lucide SVGs -> flattened stroked/filled polylines (viewBox 24).
//! Emits `icons_gen.rs`: one `pub static NAME: &[StrokePath]` per file plus
//! `lookup(name)`.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const FLAT_TOL: f64 = 0.05;

fn attr<'a>(el: &'a str, key: &str) -> Option<&'a str> {
    let pat = format!("{key}=\"");
    let i = el.find(&pat)? + pat.len();
    let j = i + el[i..].find('"')?;
    Some(&el[i..j])
}

fn num(el: &str, key: &str) -> f64 {
    attr(el, key).and_then(|v| v.parse().ok()).unwrap_or(0.0)
}

/// One SVG element -> flattened polylines `(points, closed, fill)`.
type Paths = Vec<(Vec<(f32, f32)>, bool, bool)>;

fn flatten(bez: kurbo::BezPath, fill: bool, out: &mut Paths) {
    let mut cur: Vec<(f32, f32)> = Vec::new();
    let mut closed = false;
    kurbo::flatten(bez, FLAT_TOL, |el| match el {
        kurbo::PathEl::MoveTo(p) => {
            if !cur.is_empty() {
                out.push((std::mem::take(&mut cur), closed, fill));
                closed = false;
            }
            cur.push((p.x as f32, p.y as f32));
        }
        kurbo::PathEl::LineTo(p) => cur.push((p.x as f32, p.y as f32)),
        kurbo::PathEl::ClosePath => closed = true,
        _ => {}
    });
    if !cur.is_empty() {
        out.push((cur, closed, fill));
    }
}

fn extract(svg: &str) -> Paths {
    use kurbo::Shape;
    let mut out: Paths = Vec::new();
    for tag in ["path", "rect", "circle", "ellipse", "line"] {
        let open = format!("<{tag} ");
        for el in svg.match_indices(&open).map(|(i, _)| &svg[i..]) {
            // attrs live inside this tag only — searching the remainder of
            // the file would leak a later element's `fill`/`x`/… into this one
            let el = &el[..el.find('>').unwrap_or(el.len())];
            let fill = attr(el, "fill") == Some("currentColor");
            let bez: Option<kurbo::BezPath> = match tag {
                "path" => attr(el, "d").and_then(|d| kurbo::BezPath::from_svg(d).ok()),
                "rect" => Some(
                    kurbo::RoundedRect::new(
                        num(el, "x"),
                        num(el, "y"),
                        num(el, "x") + num(el, "width"),
                        num(el, "y") + num(el, "height"),
                        num(el, "rx"),
                    )
                    .to_path(FLAT_TOL),
                ),
                "circle" => Some(
                    kurbo::Circle::new((num(el, "cx"), num(el, "cy")), num(el, "r"))
                        .to_path(FLAT_TOL),
                ),
                "ellipse" => Some(
                    kurbo::Ellipse::new(
                        (num(el, "cx"), num(el, "cy")),
                        (num(el, "rx"), num(el, "ry")),
                        0.0,
                    )
                    .to_path(FLAT_TOL),
                ),
                "line" => Some(
                    kurbo::BezPath::from_svg(&format!(
                        "M{} {}L{} {}",
                        num(el, "x1"),
                        num(el, "y1"),
                        num(el, "x2"),
                        num(el, "y2")
                    ))
                    .unwrap_or_default(),
                ),
                _ => None,
            };
            if let Some(bez) = bez {
                flatten(bez, fill, &mut out);
            }
        }
    }
    out
}

fn main() {
    println!("cargo:rerun-if-changed=icons");
    let mut out = String::from("// @generated by build.rs — do not edit\n");
    let mut lookup = String::from(
        "\npub fn lookup(name: &str) -> Option<&'static [StrokePath]> {\n    match name {\n",
    );
    let mut files: Vec<_> = fs::read_dir("icons")
        .unwrap()
        .map(|f| f.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "svg"))
        .collect();
    files.sort();
    for f in files {
        let stem = f.file_stem().unwrap().to_str().unwrap();
        let ident = stem.replace('-', "_").to_uppercase();
        let svg = fs::read_to_string(&f).unwrap();
        let paths = extract(&svg);
        assert!(!paths.is_empty(), "no geometry extracted from {stem}");
        let _ = writeln!(out, "pub static {ident}: &[StrokePath] = &[");
        for (pts, closed, fill) in &paths {
            let pts_str: Vec<String> = pts
                .iter()
                .map(|(x, y)| format!("({x:.2},{y:.2})"))
                .collect();
            let _ = writeln!(
                out,
                "    StrokePath {{ pts: &[{}], closed: {closed}, fill: {fill} }},",
                pts_str.join(",")
            );
        }
        out.push_str("];\n");
        let _ = writeln!(lookup, "        \"{stem}\" => Some({ident}),");
    }
    lookup.push_str("        _ => None,\n    }\n}\n");
    out.push_str(&lookup);
    fs::write(
        Path::new(&env::var("OUT_DIR").unwrap()).join("icons_gen.rs"),
        out,
    )
    .unwrap();
}
